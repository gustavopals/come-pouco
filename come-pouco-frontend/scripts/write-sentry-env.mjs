import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, '../src/environments/sentry.generated.ts');

const readEnv = (...names) => {
  for (const name of names) {
    const value = process.env[name]?.trim();

    if (value) {
      return value;
    }
  }

  return '';
};

const normalizeSampleRate = (value) => {
  const parsed = Number(value);

  if (!Number.isFinite(parsed)) {
    return 'undefined';
  }

  return String(Math.min(1, Math.max(0, parsed)));
};

const generated = `// Generated by scripts/write-sentry-env.mjs. Do not edit manually.
export const sentry = {
  dsn: ${JSON.stringify(readEnv('SENTRY_DSN_FRONTEND', 'PUBLIC_SENTRY_DSN_FRONTEND'))},
  release: ${JSON.stringify(readEnv('SENTRY_RELEASE', 'COMMIT_SHA', 'GIT_SHA'))},
  environment: ${JSON.stringify(readEnv('SENTRY_ENVIRONMENT', 'APP_ENV', 'NODE_ENV'))},
  tracesSampleRate: ${normalizeSampleRate(readEnv('SENTRY_TRACES_SAMPLE_RATE_FRONTEND', 'SENTRY_TRACES_SAMPLE_RATE'))} as number | undefined
};
`;

mkdirSync(dirname(outputPath), { recursive: true });

let current = '';
try {
  current = readFileSync(outputPath, 'utf8');
} catch {
  current = '';
}

if (current !== generated) {
  writeFileSync(outputPath, generated);
}
